#!/usr/bin/env python3
"""Turns the desktop app's SVG icons into Compose ImageVectors, so both apps
draw the same set. Run from the repository root:

    python3 android/tools/gen_icons.py

The icons are 24x24, stroked at 2 with round caps and joins; an element with
fill="#000" is filled as well as stroked.
"""

import pathlib
import re
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "crates/snot-desktop/assets/icons"
OUT = ROOT / "android/app/src/main/java/app/snot/ui/SnotIcons.kt"
NS = "{http://www.w3.org/2000/svg}"


def num(v):
    return float(v) if v else 0.0


def fmt(v):
    return f"{v:g}"


def circle(cx, cy, r):
    return (f"M{fmt(cx - r)},{fmt(cy)}a{fmt(r)},{fmt(r)} 0 1,0 {fmt(2 * r)},0"
            f"a{fmt(r)},{fmt(r)} 0 1,0 {fmt(-2 * r)},0Z")


def rect(x, y, w, h, rx):
    if rx <= 0:
        return f"M{fmt(x)},{fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}Z"
    return (f"M{fmt(x + rx)},{fmt(y)}h{fmt(w - 2 * rx)}a{fmt(rx)},{fmt(rx)} 0 0 1 {fmt(rx)},{fmt(rx)}"
            f"v{fmt(h - 2 * rx)}a{fmt(rx)},{fmt(rx)} 0 0 1 {fmt(-rx)},{fmt(rx)}"
            f"h{fmt(-(w - 2 * rx))}a{fmt(rx)},{fmt(rx)} 0 0 1 {fmt(-rx)},{fmt(-rx)}"
            f"v{fmt(-(h - 2 * rx))}a{fmt(rx)},{fmt(rx)} 0 0 1 {fmt(rx)},{fmt(-rx)}Z")


def elements(svg):
    for el in ET.parse(svg).getroot().iter():
        tag = el.tag.replace(NS, "")
        filled = el.get("fill") not in (None, "none")
        if tag == "path":
            yield el.get("d"), filled
        elif tag == "circle":
            yield circle(num(el.get("cx")), num(el.get("cy")), num(el.get("r"))), filled
        elif tag == "rect":
            yield rect(num(el.get("x")), num(el.get("y")), num(el.get("width")),
                       num(el.get("height")), num(el.get("rx"))), filled


def name(stem):
    return re.sub(r"(?:^|-)(\w)", lambda m: m.group(1).upper(), stem)


def main():
    out = [
        "// Generated by android/tools/gen_icons.py from crates/snot-desktop/assets/icons.",
        "// Do not edit by hand.",
        "",
        "package app.snot.ui",
        "",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "",
        "object SnotIcons {",
    ]
    for svg in sorted(SRC.glob("*.svg")):
        parts = ", ".join(f'"{d}" to {"true" if f else "false"}' for d, f in elements(svg))
        out.append(f"    val {name(svg.stem)}: ImageVector by lazy {{ icon(\"{svg.stem}\", {parts}) }}")
    out.append("}")
    OUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


main()
